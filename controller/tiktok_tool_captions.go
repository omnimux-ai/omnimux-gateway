const (
	tiktokToolMaxCaption              = 2 << 20
	tiktokToolMaxCaptionTracks        = 12
	tiktokToolMaxFetchedCaptionTracks = 6
	tiktokToolMaxTranscriptCues       = 2000
	tiktokToolCaptionTimeout          = 10 * time.Second
)

type tiktokCaptionTrack struct {
	lang            string
	languageCode    string
	format          string
	isAutoGenerated bool
	url             string
}

type tiktokTranscriptCue struct {
	StartMs int    `json:"start_ms"`
	EndMs   int    `json:"end_ms"`
	Text    string `json:"text"`
}

type tiktokTranscriptTrack struct {
	ID              string                `json:"id"`
	Lang            string                `json:"lang"`
	LanguageCode    string                `json:"language_code"`
	IsAutoGenerated bool                  `json:"is_auto_generated"`
	Cues            []tiktokTranscriptCue `json:"cues"`
}

var (
	vttInlineTagPattern = regexp.MustCompile(`<[^>]+>`)
	whitespacePattern   = regexp.MustCompile(`\s+`)
)

// tiktokCaptionHostAllowed limits server-side caption fetches to known TikTok
// CDN/web hosts plus explicit operator-configured caption CDN suffixes/hosts.
func tiktokCaptionHostAllowed(host string) bool {
	host = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(host), "."))
	if host == "" || strings.HasPrefix(host, ".") {
		return false
	}
	if tiktokMediaHostAllowed(host) || tiktokHostAllowed(host) {
		return true
	}
	rawExtra := strings.TrimSpace(common.GetEnvOrDefaultString("TIKTOK_TOOL_EXTRA_CAPTION_HOSTS", ""))
	if rawExtra == "" {
		return false
	}
	for entry := range strings.SplitSeq(rawExtra, ",") {
		entry = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(entry), "."))
		if entry == "" || strings.ContainsAny(entry, "/*?:@") {
			continue
		}
		if strings.HasPrefix(entry, ".") {
			if strings.HasSuffix(host, entry) && len(host) > len(entry) {
				return true
			}
			continue
		}
		if host == entry {
			return true
		}
	}
	return false
}

func firstCaptionHTTPURL(item gjson.Result) string {
	for _, listKey := range []string{"url_list", "UrlList"} {
		for _, entry := range item.Get(listKey).Array() {
			raw := strings.TrimSpace(entry.String())
			if parsed, err := url.Parse(raw); err == nil && parsed.Scheme == "https" && tiktokCaptionHostAllowed(parsed.Hostname()) {
				return raw
			}
		}
	}
	for _, singleKey := range []string{"url", "Url"} {
		raw := strings.TrimSpace(item.Get(singleKey).String())
		if parsed, err := url.Parse(raw); err == nil && parsed.Scheme == "https" && tiktokCaptionHostAllowed(parsed.Hostname()) {
			return raw
		}
	}
	return ""
}

func firstNonEmptyCaptionField(values ...string) string {
	for _, value := range values {
		if trimmed := strings.TrimSpace(value); trimmed != "" {
			return trimmed
		}
	}
	return ""
}

// extractTikTokCaptionTracks reads published caption tracks from an
// aweme_detail object without rejecting the post when subtitles are absent.
func extractTikTokCaptionTracks(detail gjson.Result) []tiktokCaptionTrack {
	items := detail.Get("video.cla_info.caption_infos")
	if !items.IsArray() || len(items.Array()) == 0 {
		items = detail.Get("video.subtitle_infos")
	}
	if !items.IsArray() || len(items.Array()) == 0 {
		return nil
	}
	seen := make(map[string]struct{}, tiktokToolMaxCaptionTracks)
	tracks := make([]tiktokCaptionTrack, 0, min(len(items.Array()), tiktokToolMaxCaptionTracks))
	for _, item := range items.Array() {
		if len(tracks) >= tiktokToolMaxCaptionTracks {
			break
		}
		format := strings.ToLower(strings.TrimSpace(firstNonEmptyCaptionField(
			item.Get("caption_format").String(),
			item.Get("Format").String(),
		)))
		if format != "" && format != "webvtt" && format != "vtt" {
			continue
		}
		captionURL := firstCaptionHTTPURL(item)
		if captionURL == "" {
			continue
		}
		lang := firstNonEmptyCaptionField(
			item.Get("lang").String(),
			item.Get("LanguageCodeName").String(),
			item.Get("language_code").String(),
		)
		langCode := firstNonEmptyCaptionField(
			item.Get("language_code").String(),
			lang,
		)
		if lang == "" {
			lang = "und"
			langCode = "und"
		}
		isAuto := item.Get("is_auto_generated").Bool() ||
			strings.EqualFold(strings.TrimSpace(item.Get("caption_type").String()), "asr") ||
			strings.EqualFold(strings.TrimSpace(item.Get("Source").String()), "asr")
		dedupKey := strings.ToLower(langCode) + ":" + strconv.FormatBool(isAuto)
		if _, exists := seen[dedupKey]; exists {
			continue
		}
		seen[dedupKey] = struct{}{}
		tracks = append(tracks, tiktokCaptionTrack{
			lang:            lang,
			languageCode:    langCode,
			format:          firstNonEmptyCaptionField(format, "webvtt"),
			isAutoGenerated: isAuto,
			url:             captionURL,
		})
	}
	return tracks
}

var tiktokCaptionHTTPClient = tiktokToolHTTPClient

// tiktokCaptionFetch downloads one WebVTT caption file through the
// SSRF-protected HTTP client, blocking redirects off allowlisted hosts.
var tiktokCaptionFetch = func(ctx context.Context, rawURL string) (string, error) {
	target, err := url.Parse(rawURL)
	if err != nil || target.Scheme != "https" || !tiktokCaptionHostAllowed(target.Hostname()) {
		return "", errors.New("caption host not allowed")
	}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, target.String(), nil)
	if err != nil {
		return "", err
	}
	req.Header.Set("User-Agent", "Mozilla/5.0")
	req.Header.Set("Referer", "https://www.tiktok.com/")

	baseClient := tiktokCaptionHTTPClient()
	client := *baseClient
	baseRedirect := client.CheckRedirect
	client.CheckRedirect = func(nextReq *http.Request, via []*http.Request) error {
		if nextReq.URL.Scheme != "https" || !tiktokCaptionHostAllowed(nextReq.URL.Hostname()) {
			return errors.New("caption redirect host not allowed")
		}
		if len(via) >= 5 {
			return errors.New("too many caption redirects")
		}
		if baseRedirect != nil {
			return baseRedirect(nextReq, via)
		}
		return nil
	}

	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("caption status %d", resp.StatusCode)
	}
	if resp.ContentLength > tiktokToolMaxCaption {
		return "", errors.New("caption exceeds size limit")
	}
	contentType := strings.ToLower(strings.TrimSpace(resp.Header.Get("Content-Type")))
	if strings.HasPrefix(contentType, "video/") || strings.HasPrefix(contentType, "audio/") || strings.HasPrefix(contentType, "image/") || strings.HasPrefix(contentType, "text/html") {
		return "", errors.New("unexpected caption content type")
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, tiktokToolMaxCaption+1))
	if err != nil {
		return "", err
	}
	if len(data) > tiktokToolMaxCaption {
		return "", errors.New("caption exceeds size limit")
	}
	return string(data), nil
}

func captionTrackPriority(track tiktokCaptionTrack) int {
	score := 0
	if !track.isAutoGenerated {
		score += 4
	}
	code := strings.ToLower(track.languageCode)
	if strings.HasPrefix(code, "en") || strings.HasPrefix(code, "zh") {
		score += 2
	}
	return score
}

func selectCaptionTracksForFetch(tracks []tiktokCaptionTrack) []tiktokCaptionTrack {
	if len(tracks) <= tiktokToolMaxFetchedCaptionTracks {
		return tracks
	}
	selected := make([]tiktokCaptionTrack, 0, tiktokToolMaxFetchedCaptionTracks)
	used := make([]bool, len(tracks))
	for len(selected) < tiktokToolMaxFetchedCaptionTracks {
		bestIdx := -1
		bestScore := -1
		for i, track := range tracks {
			if used[i] {
				continue
			}
			if score := captionTrackPriority(track); score > bestScore {
				bestScore = score
				bestIdx = i
			}
		}
		if bestIdx < 0 {
			break
		}
		used[bestIdx] = true
		selected = append(selected, tracks[bestIdx])
	}
	return selected
}

func fetchTikTokTranscriptTracks(ctx context.Context, captionTracks []tiktokCaptionTrack) []tiktokTranscriptTrack {
	if len(captionTracks) == 0 {
		return nil
	}
	fetchCtx, cancel := context.WithTimeout(ctx, tiktokToolCaptionTimeout)
	defer cancel()

	selected := selectCaptionTracksForFetch(captionTracks)
	results := make([]tiktokTranscriptTrack, 0, len(selected))
	seenIDs := make(map[string]int, len(selected))
	for _, track := range selected {
		raw, err := tiktokCaptionFetch(fetchCtx, track.url)
		if err != nil {
			continue
		}
		cues := parseWebVTT(raw)
		if len(cues) == 0 {
			continue
		}
		baseID := track.languageCode
		if track.isAutoGenerated {
			baseID += "-auto"
		}
		seenIDs[baseID]++
		id := baseID
		if count := seenIDs[baseID]; count > 1 {
			id = fmt.Sprintf("%s-%d", baseID, count)
		}
		results = append(results, tiktokTranscriptTrack{
			ID:              id,
			Lang:            track.lang,
			LanguageCode:    track.languageCode,
			IsAutoGenerated: track.isAutoGenerated,
			Cues:            cues,
		})
	}
	return results
}

func parseVTTTimestamp(raw string) (int, bool) {
	raw = strings.TrimSpace(strings.ReplaceAll(raw, ",", "."))
	if raw == "" {
		return 0, false
	}
	secPart := raw
	msPart := "0"
	if before, after, found := strings.Cut(raw, "."); found {
		secPart = before
		msPart = after
	}
	nonDigit := func(r rune) bool { return r < '0' || r > '9' }
	if msPart == "" || strings.IndexFunc(msPart, nonDigit) >= 0 {
		return 0, false
	}
	// Pad or truncate fractional seconds to 3-digit milliseconds.
	for len(msPart) < 3 {
		msPart += "0"
	}
	msPart = msPart[:3]
	ms, err := strconv.Atoi(msPart)
	if err != nil || ms < 0 || ms > 999 {
		return 0, false
	}

	var hours, minutes, seconds int
	parts := make([]int, 0, 3)
	for seg := range strings.SplitSeq(secPart, ":") {
		if seg == "" || strings.IndexFunc(seg, nonDigit) >= 0 {
			return 0, false
		}
		val, err := strconv.Atoi(seg)
		if err != nil || val < 0 {
			return 0, false
		}
		parts = append(parts, val)
	}
	switch len(parts) {
	case 2:
		minutes, seconds = parts[0], parts[1]
	case 3:
		hours, minutes, seconds = parts[0], parts[1], parts[2]
	default:
		return 0, false
	}
	if minutes >= 60 || seconds >= 60 {
		return 0, false
	}
	return ((hours*3600 + minutes*60 + seconds) * 1000) + ms, true
}

func parseWebVTT(raw string) []tiktokTranscriptCue {
	cleaned := strings.TrimPrefix(raw, "\uFEFF")
	cleaned = strings.ReplaceAll(cleaned, "\r\n", "\n")
	cleaned = strings.ReplaceAll(cleaned, "\r", "\n")

	blocks := strings.SplitSeq(cleaned, "\n\n")
	cues := make([]tiktokTranscriptCue, 0, 32)
	prevText := ""
	for block := range blocks {
		if len(cues) >= tiktokToolMaxTranscriptCues {
			break
		}
		block = strings.TrimSpace(block)
		if block == "" {
			continue
		}
		lines := strings.Split(block, "\n")
		first := strings.TrimSpace(lines[0])
		if strings.HasPrefix(first, "WEBVTT") || strings.HasPrefix(first, "NOTE") || strings.HasPrefix(first, "STYLE") || strings.HasPrefix(first, "REGION") {
			continue
		}
		timingIdx := -1
		for i, line := range lines {
			if strings.Contains(line, "-->") {
				timingIdx = i
				break
			}
		}
		if timingIdx < 0 || timingIdx+1 >= len(lines) {
			continue
		}
		startRaw, restRaw, _ := strings.Cut(lines[timingIdx], "-->")
		restFields := strings.Fields(strings.TrimSpace(restRaw))
		if len(restFields) == 0 {
			continue
		}
		startMs, okStart := parseVTTTimestamp(startRaw)
		endMs, okEnd := parseVTTTimestamp(restFields[0])
		if !okStart || !okEnd || endMs < startMs {
			continue
		}
		var textBuilder strings.Builder
		for _, payloadLine := range lines[timingIdx+1:] {
			stripped := vttInlineTagPattern.ReplaceAllString(payloadLine, "")
			unescaped := strings.TrimSpace(html.UnescapeString(stripped))
			if unescaped == "" {
				continue
			}
			if textBuilder.Len() > 0 {
				textBuilder.WriteByte(' ')
			}
			textBuilder.WriteString(unescaped)
		}
		cueText := strings.TrimSpace(whitespacePattern.ReplaceAllString(textBuilder.String(), " "))
		if cueText == "" || cueText == prevText {
			continue
		}
		prevText = cueText
		cues = append(cues, tiktokTranscriptCue{
			StartMs: startMs,
			EndMs:   endMs,
			Text:    cueText,
		})
	}
	return cues
}
